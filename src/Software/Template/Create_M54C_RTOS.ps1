<#
.SYNOPSIS
    Generates or updates a BladeCore-M54C (RP2354B) FreeRTOS project.

.DESCRIPTION
    Create mode (default):
        Writes main.c, CONFIG.h, FreeRTOSConfig.h, CMakeLists.txt, pico_sdk_import.cmake,
        build.py, .gitignore, .vscode/, and an empty incl/ folder for user libraries.
        Detects and installs required tools:
            - Git, Python, CMake, Ninja (via winget)
            - Raspberry Pi Pico SDK 2.2.0 (git clone into %USERPROFILE%\.pico-sdk\sdk\2.2.0)
            - ARM GNU Toolchain 14.2.rel1 (download + extract)
            - picotool 2.2.0-a4 + OpenOCD 0.12.0+dev (pico-sdk-tools release)
            - FreeRTOS-Kernel (git clone into project as submodule-like folder)
        Sets PICO_SDK_PATH and PICO_TOOLCHAIN_PATH user env vars.

    Update mode (-Update):
        Rescans incl/ under -TargetPath and rewrites the two marked regions of
        CMakeLists.txt:
            # === USER SOURCES BEGIN === ... # === USER SOURCES END ===
            # === USER INCLUDE DIRS BEGIN === ... # === USER INCLUDE DIRS END ===
        Every .c under incl/ becomes a source. Every subdirectory containing a .h
        becomes an include directory. No other files are touched.

.PARAMETER TargetPath
    Path of the project folder. In create mode it is created if missing. In update
    mode it must be an existing project generated by this script.

.PARAMETER ProjectName
    Create mode only. C identifier used as CMake target and UF2/ELF file name.
    Defaults to the leaf of TargetPath.

.PARAMETER Update
    Update mode. Rewrites the user-managed regions of CMakeLists.txt from the
    current contents of incl/ under -TargetPath. Ignored in create mode.

.PARAMETER SkipToolInstall
    Create mode only. Skip tool detection and installation.

.PARAMETER Force
    Create mode only. Overwrite existing files in TargetPath.

.EXAMPLE
    .\Create_M54C_RTOS.ps1 -TargetPath C:\Dev\MyProject -ProjectName MyProject

.EXAMPLE
    .\Create_M54C_RTOS.ps1 -TargetPath C:\Dev\MyProject -SkipToolInstall

.EXAMPLE
    .\Create_M54C_RTOS.ps1 -TargetPath C:\Dev\MyProject -Update
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true, Position = 0)]
    [string]$TargetPath,

    [Parameter(Position = 1)]
    [string]$ProjectName,

    [switch]$Update,

    [switch]$SkipToolInstall,

    [switch]$Force
)

