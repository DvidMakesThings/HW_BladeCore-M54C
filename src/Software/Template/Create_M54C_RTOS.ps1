function Write-ProjectFile {
    param(
        [string]$Path,
        [string]$Content,
        [string]$Name
    )
    $dir = Split-Path $Path -Parent
    if (-not (Test-Path $dir)) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    if ((Test-Path $Path) -and -not $Force) {
        Write-Warn2 "Exists (skipped): $Path"
        return
    }
    # Substitute the project name placeholder.
    $Content = $Content.Replace('__PROJECT_NAME__', $Name)
    # Write with UTF-8 (no BOM) and Unix line endings for portability.
    $Content = $Content -replace "`r`n", "`n"
    [System.IO.File]::WriteAllText($Path, $Content, (New-Object System.Text.UTF8Encoding($false)))
    Write-Ok "Wrote $Path"
}

function Add-FreeRTOSKernel {
    param([string]$ProjectDir)
    $target = Join-Path $ProjectDir 'FreeRTOS-Kernel'
    if (Test-Path (Join-Path $target 'portable\ThirdParty\GCC\RP2350_ARM_NTZ')) {
        Write-Ok "FreeRTOS-Kernel already present at $target"
        return
    }
    if (-not (Test-Command 'git')) {
        Write-Warn2 'Git not available. Clone FreeRTOS-Kernel manually into the project directory.'
        return
    }
    Write-Step "Cloning FreeRTOS-Kernel ($FREERTOS_KERNEL_BRANCH) into $target"
    $rc = Invoke-Native 'git' @('clone', '--depth', '1', '--branch', $FREERTOS_KERNEL_BRANCH, $FREERTOS_KERNEL_REPO, $target)
    if ($rc -ne 0) {
        Write-Warn2 "git clone FreeRTOS-Kernel failed (exit $rc). Fetch manually before building."
    }
}

function Add-InclFolder {
    param([string]$ProjectDir)
    $incl = Join-Path $ProjectDir 'incl'
    if (-not (Test-Path $incl)) {
        New-Item -ItemType Directory -Path $incl -Force | Out-Null
    }
    $keep = Join-Path $incl '.gitkeep'
    if (-not (Test-Path $keep)) {
        [System.IO.File]::WriteAllText($keep, '', (New-Object System.Text.UTF8Encoding($false)))
    }
    Write-Ok "Ensured incl\ folder at $incl"
}

function Update-ProjectCMake {
    param([string]$ProjectDir)

    $cmakePath = Join-Path $ProjectDir 'CMakeLists.txt'
    if (-not (Test-Path $cmakePath)) {
        throw "CMakeLists.txt not found at $cmakePath"
    }
    $incl = Join-Path $ProjectDir 'incl'
    if (-not (Test-Path $incl)) {
        Write-Warn2 "incl\ folder does not exist; creating empty one at $incl"
        New-Item -ItemType Directory -Path $incl -Force | Out-Null
    }

    # Discover user sources and header directories under incl\.
    $projRoot = (Resolve-Path $ProjectDir).Path.TrimEnd('\')
    function _RelPath($full) {
        $f = $full.TrimEnd('\')
        if ($f.StartsWith($projRoot, [StringComparison]::OrdinalIgnoreCase)) {
            return $f.Substring($projRoot.Length).TrimStart('\')
        }
        return $f
    }

    $sources = @(
        Get-ChildItem -Path $incl -Recurse -File -Filter '*.c' -ErrorAction SilentlyContinue |
            ForEach-Object { (_RelPath $_.FullName).Replace('\', '/') } |
            Sort-Object
    )
    $inclRoot = (Resolve-Path $incl).Path.TrimEnd('\')
    $headerDirs = @(
        Get-ChildItem -Path $incl -Recurse -File -Filter '*.h' -ErrorAction SilentlyContinue |
            ForEach-Object { $_.Directory.FullName.TrimEnd('\') } |
            Sort-Object -Unique |
            Where-Object { $_ -ne $inclRoot } |
            ForEach-Object { '${CMAKE_CURRENT_LIST_DIR}/' + (_RelPath $_).Replace('\', '/') }
    )

    $srcBlock = if ($sources.Count -gt 0) {
        ($sources | ForEach-Object { "    $_" }) -join "`n"
    } else { '' }

    $incBlock = if ($headerDirs.Count -gt 0) {
        ($headerDirs | ForEach-Object { "    $_" }) -join "`n"
    } else { '' }

    $text = [System.IO.File]::ReadAllText($cmakePath)

    $srcPattern = '(?s)(# === USER SOURCES BEGIN ===.*?\n)(.*?)(\s*# === USER SOURCES END ===)'
    $incPattern = '(?s)(# === USER INCLUDE DIRS BEGIN ===.*?\n)(.*?)(\s*# === USER INCLUDE DIRS END ===)'

    if ($text -notmatch $srcPattern) {
        throw 'USER SOURCES markers not found in CMakeLists.txt. Project was not created by this script or the markers were removed.'
    }
    if ($text -notmatch $incPattern) {
        throw 'USER INCLUDE DIRS markers not found in CMakeLists.txt.'
    }

    $newSrc = if ($srcBlock) { "`$1$srcBlock`n`$3" } else { "`$1`$3" }
    $newInc = if ($incBlock) { "`$1$incBlock`n`$3" } else { "`$1`$3" }

    $text = [regex]::Replace($text, $srcPattern, $newSrc)
    $text = [regex]::Replace($text, $incPattern, $newInc)

    [System.IO.File]::WriteAllText($cmakePath, $text, (New-Object System.Text.UTF8Encoding($false)))

    Write-Ok ("CMakeLists.txt updated: {0} source(s), {1} include dir(s)" -f $sources.Count, $headerDirs.Count)
    if ($sources.Count -gt 0) {
        Write-Host '  Sources:' -ForegroundColor Cyan
        $sources | ForEach-Object { Write-Host "    $_" }
    }
    if ($headerDirs.Count -gt 0) {
        Write-Host '  Include dirs:' -ForegroundColor Cyan
        $headerDirs | ForEach-Object { Write-Host "    $_" }
    }
}

