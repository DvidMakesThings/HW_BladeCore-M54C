function Install-BaseTools {
    Write-Step 'Checking base tools (Git, Python, CMake, Ninja)...'

    $prev = $ErrorActionPreference
    $ErrorActionPreference = 'SilentlyContinue'
    try {
        if (-not (Test-Command 'git')) {
            Write-Warn2 'Git not found.'
            Invoke-Winget 'Git.Git' | Out-Null
        }
        else {
            $v = (& git --version 2>&1 | Out-String).Trim()
            Write-Ok "Git: $v"
        }

        # Real Python detection: never invokes python3, only checks Get-Command
        # and filters out the Windows Store App Execution Alias stub.
        $py = Get-RealPythonCommand
        if ($py) {
            Write-Ok "Python ($($py.Name)): $($py.Path)"
        }
        else {
            Write-Warn2 'No real Python interpreter on PATH (Windows Store alias skipped). build.py requires Python 3.'
            Invoke-Winget 'Python.Python.3.12' | Out-Null
        }

        if (-not (Test-Command 'cmake')) {
            Write-Warn2 'System CMake not on PATH (Pico SDK bundle will still be installed below).'
        }
        else {
            $v = ((& cmake --version 2>&1 | Out-String) -split "`n" | Select-Object -First 1).Trim()
            Write-Ok "CMake: $v"
        }

        if (-not (Test-Command 'ninja')) {
            Write-Warn2 'System Ninja not on PATH (Pico SDK bundle will still be installed below).'
        }
        else {
            $v = (& ninja --version 2>&1 | Out-String).Trim()
            Write-Ok "Ninja: $v"
        }
    }
    finally {
        $ErrorActionPreference = $prev
    }
}

function Install-CMakeBundle {
    $exe = Join-Path $CMAKE_DIR 'bin\cmake.exe'
    if (Test-Path $exe) {
        Write-Ok "CMake $CMAKE_VERSION already at $CMAKE_DIR"
        Add-UserPath (Join-Path $CMAKE_DIR 'bin')
        return
    }
    if (Test-Path $CMAKE_DIR) {
        Write-Warn2 "CMake install at $CMAKE_DIR is incomplete; wiping and reinstalling."
        Remove-Item -Recurse -Force $CMAKE_DIR
    }
    $ver = $CMAKE_VERSION.TrimStart('v')
    $url = "https://github.com/Kitware/CMake/releases/download/$CMAKE_VERSION/cmake-$ver-windows-x86_64.zip"
    $zip = Join-Path $env:TEMP "cmake-$ver.zip"
    $stage = Join-Path $env:TEMP "cmake-$ver-stage"
    Save-File $url $zip
    if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
    Expand-Zip $zip $stage
    $root = Get-ChildItem $stage -Directory | Select-Object -First 1
    if (-not $root) { throw "CMake archive layout unexpected: no top-level directory in $stage" }
    New-Item -ItemType Directory -Force -Path $CMAKE_DIR | Out-Null
    Copy-Item -Path (Join-Path $root.FullName '*') -Destination $CMAKE_DIR -Recurse -Force
    Remove-Item -Recurse -Force $stage, $zip
    if (-not (Test-Path $exe)) { throw "CMake install failed: $exe not present after extract." }
    Add-UserPath (Join-Path $CMAKE_DIR 'bin')
    Write-Ok "CMake bundle installed at $CMAKE_DIR"
}

