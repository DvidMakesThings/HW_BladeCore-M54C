{
    gpio_put(PIN_CAN_CS, 0);
    if (receive != NULL)
    {
        spi_write_read_blocking(CAN_SPI_INSTANCE, transmit, receive, length);
    }
    else
    {
        spi_write_blocking(CAN_SPI_INSTANCE, transmit, length);
    }
