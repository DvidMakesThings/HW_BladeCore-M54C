function Write-Step   ($msg) { Write-Host "[*] $msg" -ForegroundColor Cyan }
function Write-Ok     ($msg) { Write-Host "[+] $msg" -ForegroundColor Green }
function Write-Warn2  ($msg) { Write-Host "[!] $msg" -ForegroundColor Yellow }
function Write-Fail   ($msg) { Write-Host "[X] $msg" -ForegroundColor Red }

function Test-Command($name) {
    return [bool](Get-Command $name -ErrorAction SilentlyContinue)
}

# Return the name of a Python command on PATH that is a REAL executable, not
# the Windows Store App Execution Alias stub (whose Source path lives under
# %LOCALAPPDATA%\Microsoft\WindowsApps\ and prints "Python not found" instead
# of running). Never invokes the command, only checks Get-Command.Source.
function Get-RealPythonCommand {
    foreach ($name in @('py', 'python', 'python3')) {
        $cmd = Get-Command $name -ErrorAction SilentlyContinue
        if (-not $cmd) { continue }
        if ($cmd.Source -match '\\WindowsApps\\') { continue }
        return [pscustomobject]@{ Name = $name; Path = $cmd.Source }
    }
    return $null
}

# Run a native command tolerating stderr output under strict mode.
# Returns the exit code without throwing. ($Args is a PS automatic variable, use $Arguments.)
function Invoke-Native {
    param([string]$Exe, [string[]]$Arguments)
    $prev = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        & $Exe @Arguments 2>&1 | ForEach-Object { Write-Host $_ }
        return $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prev
    }
}

function Invoke-Winget($id) {
    if (-not (Test-Command 'winget')) {
        Write-Warn2 "winget not available; skipping '$id'. Install manually if needed."
        return $false
    }
    Write-Step "winget install $id"
    & winget install --id $id --exact --accept-source-agreements --accept-package-agreements --silent
    return ($LASTEXITCODE -eq 0)
}

function Save-File($url, $dest) {
    Write-Step "Downloading $url"
    $tmpDir = Split-Path $dest -Parent
    if (-not (Test-Path $tmpDir)) { New-Item -ItemType Directory -Path $tmpDir -Force | Out-Null }
    # Use TLS 1.2 for older PowerShell 5.1
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest -Uri $url -OutFile $dest -UseBasicParsing
}

function Expand-Zip($zip, $dest) {
    Write-Step "Extracting $zip -> $dest"
    if (-not (Test-Path $dest)) { New-Item -ItemType Directory -Path $dest -Force | Out-Null }
    Expand-Archive -Path $zip -DestinationPath $dest -Force
}

function Add-UserPath($dir) {
    $current = [Environment]::GetEnvironmentVariable('Path', 'User')
    if ($null -eq $current) { $current = '' }
    $parts = $current -split ';' | Where-Object { $_ -ne '' }
    if ($parts -notcontains $dir) {
        Write-Step "Adding to User PATH: $dir"
        $new = ($parts + $dir) -join ';'
        [Environment]::SetEnvironmentVariable('Path', $new, 'User')
    }
    if (($env:Path -split ';') -notcontains $dir) {
        $env:Path = "$dir;$env:Path"
    }
}

function Set-UserEnv($name, $value) {
    Write-Step "Setting user env: $name = $value"
    [Environment]::SetEnvironmentVariable($name, $value, 'User')
    Set-Item -Path "Env:$name" -Value $value
}

